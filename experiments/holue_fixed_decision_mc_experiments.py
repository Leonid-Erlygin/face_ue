#!/usr/bin/env python3
"""HolUE mean-embedding versus Monte-Carlo uncertainty with fixed OSR decisions.

Scientific question
-------------------
The ordinary ``M=0`` versus ``M>0`` HolUE comparison is confounded because
``MonteCarloPredictiveProb.predict()`` uses the same posterior that is used to
compute the KL uncertainty features.  Changing ``M`` can therefore change both
(1) the OSR decision and (2) its uncertainty estimate.

This experiment isolates (2):

1. Run the normalized dissertation HolUE system with ``base_M=0`` normally.
   Its test decisions, validation decisions, test gallery concentration and
   validation gallery concentration are frozen.
2. Recompute only the two HolUE KL features with ``mc_M`` Monte-Carlo samples,
   while reusing the *same* gallery concentrations and temperature.
3. Train a fresh HolUE calibration transform on the MC KL features, but use
   correctness labels generated by the frozen ``M=0`` validation decisions.
4. Evaluate the calibrated MC uncertainty against the frozen ``M=0`` test
   decisions.  The MC posterior's counterfactual decisions are recorded only as
   a diagnostic and are never used for labels or metrics.

The main output is ``tables/fixed_decision_mc_comparison.csv``.  Because MC
integration is stochastic, the configured seeds are run independently and an
aggregate table is written to ``fixed_decision_mc_summary.csv``.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List

import hydra
import numpy as np
import pandas as pd
from hydra.utils import instantiate
from omegaconf import OmegaConf

from evaluation.metrics import FrrFarIdent
from evaluation.reproducibility import seed_everything
from experiments.holue_temperature_scaling_experiments import (
    find_holue_method_cfg,
    fractions_from_cfg,
    instantiate_list,
    pooled_arrays,
    prepare_holue_cfg,
    raw_kl_from_pooled,
    recognition_metrics,
    run_full_variant,
    safe_spearman,
    sampled_rank_inversion_rate,
    slugify,
    uncertainty_metrics,
)


def decisions_from_mean_probs(mean_probs: np.ndarray):
    """Return the standard HolUE identity/reject decision from gallery masses."""
    probs = np.asarray(mean_probs, dtype=np.float64)
    predicted_id = np.argmax(probs, axis=-1).astype(int)
    oog_prob = 1.0 - np.sum(probs, axis=-1, keepdims=True)
    all_prob = np.concatenate([probs, oog_prob], axis=-1)
    was_rejected = np.argmax(all_prob, axis=-1) == (all_prob.shape[-1] - 1)
    return predicted_id, np.asarray(was_rejected, dtype=bool)


def error_calc_from_fixed_decisions(
    predicted_id: np.ndarray,
    was_rejected: np.ndarray,
    g_unique_ids: np.ndarray,
    probe_unique_ids: np.ndarray,
):
    error_calc = FrrFarIdent()
    error_calc(
        np.asarray(predicted_id, dtype=int),
        np.asarray(was_rejected, dtype=bool),
        np.asarray(g_unique_ids),
        np.asarray(probe_unique_ids),
    )
    return error_calc


def calibration_pooled_arrays(recognition_method) -> Dict[str, np.ndarray]:
    """Expose the already-pooled HolUE validation arrays created in setup()."""
    if not hasattr(recognition_method, "probe_pooled_templates_calib"):
        raise RuntimeError("HolUE calibration arrays are unavailable.")
    if not hasattr(recognition_method, "gallery_pooled_templates_calib"):
        raise RuntimeError("HolUE calibration gallery arrays are unavailable.")

    probe = recognition_method.probe_pooled_templates_calib["g1"]
    gallery = recognition_method.gallery_pooled_templates_calib["g1"]
    return {
        "probe_feats": np.asarray(probe["template_pooled_features"], dtype=np.float64),
        "probe_unc": np.asarray(probe["template_pooled_data_unc"], dtype=np.float64),
        "gallery_feats": np.asarray(
            gallery["template_pooled_features"], dtype=np.float64
        ),
        "gallery_unc": np.asarray(
            gallery["template_pooled_data_unc"], dtype=np.float64
        ),
        "g_unique_ids": np.asarray(gallery["template_subject_ids_sorted"]),
        "probe_unique_ids": np.asarray(probe["template_subject_ids_sorted"]),
    }


def configure_calibrator_log_dir(calibrator, path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)
    if hasattr(calibrator, "log_dir"):
        calibrator.log_dir = str(path)


def counterfactual_decision_disagreement(
    mean_probs: np.ndarray,
    fixed_predicted_id: np.ndarray,
    fixed_was_rejected: np.ndarray,
) -> float:
    pred, reject = decisions_from_mean_probs(mean_probs)
    return float(
        np.mean(
            np.logical_or(
                pred != np.asarray(fixed_predicted_id),
                reject != np.asarray(fixed_was_rejected),
            )
        )
    )


def save_csv(rows: List[Dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(path, index=False)
    print(f"[saved] {path}")


def build_summary(comparison: pd.DataFrame) -> pd.DataFrame:
    """Aggregate MC seeds and report deltas relative to fixed-decision M=0."""
    keys = ["dataset", "far", "beta", "T"]
    metrics = ["prr_f1", "error_auroc", "error_auprc"]
    rows: List[Dict[str, Any]] = []

    for group_key, group in comparison.groupby(keys, dropna=False):
        dataset, far, beta, T = group_key
        base = group[group["estimator"] == "M0 calibrated"]
        mc = group[np.logical_and(group["feature_M"] > 0, group["decisions"] == "fixed M0")]
        if len(base) != 1 or len(mc) == 0:
            continue

        row: Dict[str, Any] = {
            "dataset": dataset,
            "far": float(far),
            "beta": float(beta),
            "T": float(T),
            "mc_seed_count": int(len(mc)),
            "fixed_f1": float(base.iloc[0]["f1"]),
            "fixed_fnir": float(base.iloc[0]["fnir"]),
            "fixed_fpir": float(base.iloc[0]["fpir"]),
        }
        for metric in metrics:
            base_value = float(base.iloc[0][metric])
            mc_values = mc[metric].to_numpy(dtype=float)
            row[f"m0_{metric}"] = base_value
            row[f"m16_{metric}_mean"] = float(np.mean(mc_values))
            row[f"m16_{metric}_std"] = float(np.std(mc_values, ddof=0))
            row[f"delta_m16_minus_m0_{metric}"] = float(np.mean(mc_values) - base_value)

        row["counterfactual_decision_disagreement_mean"] = float(
            mc["counterfactual_decision_disagreement_rate"].mean()
        )
        row["counterfactual_decision_disagreement_std"] = float(
            mc["counterfactual_decision_disagreement_rate"].std(ddof=0)
        )
        rows.append(row)

    return pd.DataFrame(rows)


@hydra.main(
    config_path=str(Path(__file__).resolve().parents[1] / "configs/uncertainty_benchmark"),
    config_name="holue_fixed_decision_mc_bio",
    version_base="1.2",
)
def main(cfg):
    seed = int(cfg.get("seed", 777))
    deterministic = bool(cfg.get("deterministic", True))
    seed_everything(seed=seed, deterministic=deterministic)

    study = cfg.holue_fixed_decision_mc_study
    temp_study = cfg.holue_temperature_study
    base_M = int(study.get("base_M", 0))
    mc_M = int(study.get("mc_M", 16))
    if base_M != 0:
        raise ValueError(
            "This experiment is defined around the dissertation HolUE M=0 recognizer; "
            f"got base_M={base_M}."
        )
    if mc_M <= 0:
        raise ValueError(f"mc_M must be positive, got {mc_M}.")

    if "published_T" in temp_study:
        T = float(temp_study.published_T)
    else:
        T = float(find_holue_method_cfg(cfg).recognition_method.get("predict_T", 1.0))

    mc_seeds = [int(x) for x in study.get("mc_seeds", [seed])]
    mc_num_workers = int(study.get("mc_num_workers", 1))
    rank_pairs = int(study.get("rank_pairs", 200000))

    out_dir = Path(cfg.exp_dir)
    tables_dir = out_dir / "tables"
    per_example_dir = out_dir / "per_example_npz"
    calibrator_log_dir = out_dir / "calibrator_logs"
    tables_dir.mkdir(parents=True, exist_ok=True)
    per_example_dir.mkdir(parents=True, exist_ok=True)

    fractions = fractions_from_cfg(cfg)
    datasets = instantiate_list(cfg.test_datasets)
    base_holue_cfg = find_holue_method_cfg(cfg)

    comparison_rows: List[Dict[str, Any]] = []
    ranking_rows: List[Dict[str, Any]] = []
    feature_rows: List[Dict[str, Any]] = []

    for dataset in datasets:
        dataset_name = str(dataset.dataset_name)
        for far_raw in cfg.far_list:
            far = float(far_raw)
            for beta_raw in cfg.beta_list:
                beta = float(beta_raw)
                print("=" * 100)
                print(
                    f"[HolUEFixedDecisionMC] dataset={dataset_name} far={far} "
                    f"beta={beta} T={T} base_M={base_M} mc_M={mc_M}"
                )
                print("=" * 100)

                # ----------------------------------------------------------
                # 1. Run the dissertation M=0 HolUE system.  These decisions
                #    define the experiment and never change below.
                # ----------------------------------------------------------
                base_method_cfg = prepare_holue_cfg(
                    base_holue_cfg,
                    mode="normalized",
                    T=T,
                    M=base_M,
                    use_calibrator=True,
                    mc_num_workers=mc_num_workers,
                )
                base_tt, base_result = run_full_variant(
                    cfg,
                    dataset=dataset,
                    method_cfg=base_method_cfg,
                    far=far,
                    beta=beta,
                    variant_name="HolUE M0 fixed recognizer",
                    out_dir=out_dir,
                )
                base_rm = base_result["recognition_method"]

                if not hasattr(base_rm, "gallery_kappa_calib"):
                    raise RuntimeError(
                        "MonteCarloPredictiveProb must store gallery_kappa_calib. "
                        "Apply the full holue_fixed_decision_mc.patch before running."
                    )

                fixed_predicted_id = np.asarray(base_result["predicted_id"], dtype=int)
                fixed_was_rejected = np.asarray(base_result["was_rejected"], dtype=bool)
                g_unique_ids = np.asarray(base_result["g_unique_ids"])
                probe_unique_ids = np.asarray(base_result["probe_unique_ids"])

                # M=0 validation decisions used to train *both* uncertainty
                # calibrators, so calibration labels are identical.
                fixed_val_predicted_id, fixed_val_was_rejected = decisions_from_mean_probs(
                    base_rm.mean_probs_calib
                )
                val_error_calc = error_calc_from_fixed_decisions(
                    fixed_val_predicted_id,
                    fixed_val_was_rejected,
                    base_rm.g_unique_ids_calib,
                    base_rm.probe_unique_ids_calib,
                )
                test_error_calc = error_calc_from_fixed_decisions(
                    fixed_predicted_id,
                    fixed_was_rejected,
                    g_unique_ids,
                    probe_unique_ids,
                )

                fixed_recognition = recognition_metrics(base_result)
                base_unc_metrics = uncertainty_metrics(
                    uncertainty=base_result["predicted_unc"],
                    predicted_id=fixed_predicted_id,
                    was_rejected=fixed_was_rejected,
                    g_unique_ids=g_unique_ids,
                    probe_unique_ids=probe_unique_ids,
                    fractions=fractions,
                    seed=seed,
                )
                comparison_rows.append(
                    {
                        "dataset": dataset_name,
                        "far": far,
                        "beta": beta,
                        "T": T,
                        "base_M": base_M,
                        "feature_M": base_M,
                        "mc_seed": seed,
                        "estimator": "M0 calibrated",
                        "decisions": "fixed M0",
                        "counterfactual_decision_disagreement_rate": 0.0,
                        **fixed_recognition,
                        **base_unc_metrics,
                    }
                )

                test_arrays = pooled_arrays(base_tt)
                val_arrays = calibration_pooled_arrays(base_rm)
                kappa_input_scale = float(getattr(base_rm, "kappa_input_scale", 1.0))
                test_gallery_kappa = float(base_rm.gallery_kappa)
                val_gallery_kappa = float(base_rm.gallery_kappa_calib)

                stem = (
                    f"{slugify(dataset_name)}_far_{far}_beta_{beta}_T_{T}"
                )
                np.savez(
                    per_example_dir / f"{stem}_M0_fixed.npz",
                    predicted_id=fixed_predicted_id,
                    was_rejected=fixed_was_rejected,
                    predicted_unc=np.asarray(base_result["predicted_unc"]),
                    probe_unique_ids=probe_unique_ids,
                    g_unique_ids=g_unique_ids,
                    val_predicted_id=fixed_val_predicted_id,
                    val_was_rejected=fixed_val_was_rejected,
                    kl_1=np.asarray(base_rm.kl_1),
                    kl_2=np.asarray(base_rm.kl_2),
                    kl_1_calib=np.asarray(base_rm.kl_1_calib),
                    kl_2_calib=np.asarray(base_rm.kl_2_calib),
                    test_gallery_kappa=test_gallery_kappa,
                    validation_gallery_kappa=val_gallery_kappa,
                )

                # ----------------------------------------------------------
                # 2. MC KL features.  They get their own calibrator, but both
                #    training labels and test metrics use the fixed M=0
                #    decisions above.  MC mean_probs are diagnostic only.
                # ----------------------------------------------------------
                for mc_seed in mc_seeds:
                    val_mc = raw_kl_from_pooled(
                        base_holue_cfg,
                        val_arrays,
                        mode="normalized",
                        T=T,
                        M=mc_M,
                        beta=beta,
                        gallery_kappa=val_gallery_kappa,
                        kappa_input_scale=kappa_input_scale,
                        seed=mc_seed,
                        mc_num_workers=mc_num_workers,
                    )
                    test_mc = raw_kl_from_pooled(
                        base_holue_cfg,
                        test_arrays,
                        mode="normalized",
                        T=T,
                        M=mc_M,
                        beta=beta,
                        gallery_kappa=test_gallery_kappa,
                        kappa_input_scale=kappa_input_scale,
                        seed=mc_seed + 100000,
                        mc_num_workers=mc_num_workers,
                    )

                    calibration_cfg = base_holue_cfg.recognition_method.get(
                        "calibration_transform", None
                    )
                    if calibration_cfg is None:
                        raise RuntimeError(
                            "Fixed-decision MC study requires the HolUE calibration transform."
                        )
                    calibrator = instantiate(calibration_cfg)
                    configure_calibrator_log_dir(
                        calibrator,
                        calibrator_log_dir / f"{stem}_M{mc_M}_seed_{mc_seed}",
                    )
                    calibrator.train_calibration_parameters(
                        val_mc["kl_1"],
                        val_mc["kl_2"],
                        val_error_calc,
                        dataset_name=str(base_rm.calibration_set.dataset_name),
                        far=far,
                    )
                    mc_unc = calibrator.apply_calibration_transform(
                        test_mc["kl_1"],
                        test_mc["kl_2"],
                        test_error_calc,
                        dataset_name=dataset_name,
                        far=far,
                    )
                    mc_unc = np.asarray(mc_unc, dtype=np.float64).reshape(-1)

                    mc_metrics = uncertainty_metrics(
                        uncertainty=mc_unc,
                        predicted_id=fixed_predicted_id,
                        was_rejected=fixed_was_rejected,
                        g_unique_ids=g_unique_ids,
                        probe_unique_ids=probe_unique_ids,
                        fractions=fractions,
                        seed=seed,
                    )
                    cf_disagreement = counterfactual_decision_disagreement(
                        test_mc["mean_probs"],
                        fixed_predicted_id,
                        fixed_was_rejected,
                    )
                    comparison_rows.append(
                        {
                            "dataset": dataset_name,
                            "far": far,
                            "beta": beta,
                            "T": T,
                            "base_M": base_M,
                            "feature_M": mc_M,
                            "mc_seed": mc_seed,
                            "estimator": f"M{mc_M} calibrated, fixed M0 decisions",
                            "decisions": "fixed M0",
                            "counterfactual_decision_disagreement_rate": cf_disagreement,
                            **fixed_recognition,
                            **mc_metrics,
                        }
                    )

                    ranking_rows.append(
                        {
                            "dataset": dataset_name,
                            "far": far,
                            "beta": beta,
                            "T": T,
                            "mc_seed": mc_seed,
                            "comparison": f"M0_calibrated_vs_M{mc_M}_calibrated_fixed_decisions",
                            "spearman": safe_spearman(
                                base_result["predicted_unc"], mc_unc
                            ),
                            "rank_inversion_rate": sampled_rank_inversion_rate(
                                base_result["predicted_unc"],
                                mc_unc,
                                num_pairs=rank_pairs,
                                seed=mc_seed,
                            ),
                        }
                    )

                    base_kl1 = np.asarray(base_rm.kl_1, dtype=np.float64).reshape(-1)
                    base_kl2 = np.asarray(base_rm.kl_2, dtype=np.float64).reshape(-1)
                    feature_rows.append(
                        {
                            "dataset": dataset_name,
                            "far": far,
                            "beta": beta,
                            "T": T,
                            "mc_seed": mc_seed,
                            "mean_abs_delta_kl1": float(
                                np.mean(np.abs(test_mc["kl_1"] - base_kl1))
                            ),
                            "mean_abs_delta_kl2": float(
                                np.mean(np.abs(test_mc["kl_2"] - base_kl2))
                            ),
                            "kl1_correlation": safe_spearman(base_kl1, test_mc["kl_1"]),
                            "kl2_correlation": safe_spearman(base_kl2, test_mc["kl_2"]),
                            "counterfactual_decision_disagreement_rate": cf_disagreement,
                        }
                    )

                    np.savez(
                        per_example_dir / f"{stem}_M{mc_M}_seed_{mc_seed}.npz",
                        # These are the only decisions used for labels/metrics.
                        fixed_predicted_id=fixed_predicted_id,
                        fixed_was_rejected=fixed_was_rejected,
                        predicted_unc=mc_unc,
                        probe_unique_ids=probe_unique_ids,
                        g_unique_ids=g_unique_ids,
                        # MC posterior is stored only to audit the confounding
                        # that would occur if its decisions were used.
                        mc_mean_probs=np.asarray(test_mc["mean_probs"]),
                        mc_kl_1=np.asarray(test_mc["kl_1"]),
                        mc_kl_2=np.asarray(test_mc["kl_2"]),
                        mc_val_kl_1=np.asarray(val_mc["kl_1"]),
                        mc_val_kl_2=np.asarray(val_mc["kl_2"]),
                        counterfactual_decision_disagreement_rate=cf_disagreement,
                        test_gallery_kappa=test_gallery_kappa,
                        validation_gallery_kappa=val_gallery_kappa,
                    )

    comparison_df = pd.DataFrame(comparison_rows)
    comparison_df.to_csv(tables_dir / "fixed_decision_mc_comparison.csv", index=False)
    print(f"[saved] {tables_dir / 'fixed_decision_mc_comparison.csv'}")

    summary_df = build_summary(comparison_df)
    summary_df.to_csv(tables_dir / "fixed_decision_mc_summary.csv", index=False)
    print(f"[saved] {tables_dir / 'fixed_decision_mc_summary.csv'}")

    save_csv(ranking_rows, tables_dir / "fixed_decision_mc_ranking.csv")
    save_csv(feature_rows, tables_dir / "fixed_decision_mc_feature_shift.csv")

    manifest = {
        "protocol": (
            "M=0 HolUE recognition decisions and validation correctness labels are frozen. "
            f"M={mc_M} changes only KL-feature integration; it uses the same T, test "
            "gallery concentration and validation gallery concentration as the M=0 system. "
            "A fresh calibration transform is trained on MC KL features with M=0 validation "
            "decision labels. Counterfactual MC decisions are diagnostic only."
        ),
        "base_M": base_M,
        "mc_M": mc_M,
        "T": T,
        "mc_seeds": mc_seeds,
        "mc_num_workers": mc_num_workers,
        "rank_pairs": rank_pairs,
        "hydra_config": OmegaConf.to_container(cfg, resolve=True),
    }
    with open(out_dir / "study_manifest.json", "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)
    print(f"[saved] {out_dir / 'study_manifest.json'}")


if __name__ == "__main__":
    main()
