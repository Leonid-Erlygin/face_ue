def slugify(value: str) -> str:
    value = str(value).replace("+", "_plus_").replace("@", "_at_")
    value = re.sub(r"[^a-zA-Z0-9_.-]+", "_", value)
    value = re.sub(r"_+", "_", value)
    return value.strip("_")


def copy_cfg(node):
    return OmegaConf.create(OmegaConf.to_container(node, resolve=True))


def find_holue_method_cfg(cfg):
    matches = [m for m in cfg.open_set_identification_methods if str(m.pretty_name) == "HolUE"]
    if len(matches) != 1:
        raise ValueError(f"Expected exactly one HolUE method config, found {len(matches)}")
    return matches[0]


def set_cfg(node, key: str, value: Any) -> None:
    OmegaConf.update(node, key, value, force_add=True)


def prepare_holue_cfg(
    base_cfg,
    *,
    mode: str,
    T: float,
    M: int,
    gallery_kappa: float | None = None,
    use_calibrator: bool = True,
    mc_num_workers: int = 1,
):
    cfg = copy_cfg(base_cfg)
    set_cfg(cfg, "recognition_method.temperature_scaling_mode", str(mode))
    set_cfg(cfg, "recognition_method.predict_T", float(T))
    set_cfg(cfg, "recognition_method.M", int(M))
    set_cfg(cfg, "recognition_method.mc_num_workers", int(mc_num_workers))
    if gallery_kappa is not None:
        set_cfg(cfg, "recognition_method.gallery_kappa", float(gallery_kappa))

    if not use_calibrator:
        set_cfg(cfg, "recognition_method.calibration_set", None)
        set_cfg(cfg, "recognition_method.calibration_transform", None)
    return cfg


def configure_private_log_dir(recognition_method, path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)
    if hasattr(recognition_method, "log_dir"):
        recognition_method.log_dir = str(path)
    transform = getattr(recognition_method, "calibration_transform", None)
    if transform is not None and hasattr(transform, "log_dir"):
        transform.log_dir = str(path)


def run_full_variant(
    cfg,
    *,
    dataset,
    method_cfg,
    far: float,
    beta: float,
    variant_name: str,
    out_dir: Path,
):
    recognition_method = instantiate(method_cfg.recognition_method)
    maybe_attach_calibration_set(cfg, recognition_method, dataset.dataset_name)
    recognition_method.far = float(far)
    recognition_method.beta = float(beta)

    method_name = (
        f"{slugify(variant_name)}_dataset_{slugify(dataset.dataset_name)}"
        f"_far_{far}_beta_{beta}"
    )
    configure_private_log_dir(
        recognition_method,
        out_dir / "calibrator_logs" / method_name,
    )

    tt = build_tester(
        cfg=cfg,
        method_cfg=method_cfg,
        test_dataset=dataset,
        recognition_method=recognition_method,
        method_name=method_name,
        pretty_name=variant_name,
    )
    result = run_method_raw(tt, gallery_name="g1")
    return tt, result


def pooled_arrays(tt, gallery_name: str = "g1") -> Dict[str, np.ndarray]:
    return {
        "probe_feats": np.asarray(
            tt.probe_pooled_templates[gallery_name]["template_pooled_features"],
            dtype=np.float64,
        ),
        "probe_unc": np.asarray(
            tt.probe_pooled_templates[gallery_name]["template_pooled_data_unc"],
            dtype=np.float64,
        ),
        "gallery_feats": np.asarray(
            tt.gallery_pooled_templates[gallery_name]["template_pooled_features"],
            dtype=np.float64,
        ),
        "gallery_unc": np.asarray(
            tt.gallery_pooled_templates[gallery_name]["template_pooled_data_unc"],
            dtype=np.float64,
        ),
        "g_unique_ids": np.asarray(
            tt.gallery_pooled_templates[gallery_name]["template_subject_ids_sorted"]
        ),
        "probe_unique_ids": np.asarray(
            tt.probe_pooled_templates[gallery_name]["template_subject_ids_sorted"]
        ),
    }


def fractions_from_cfg(cfg) -> np.ndarray:
    return np.linspace(
        float(cfg.rejection_fractions[0]),
        float(cfg.rejection_fractions[1]),
        int(cfg.rejection_fractions[2]),
    )


def uncertainty_metrics(
    *,
    uncertainty: np.ndarray,
    predicted_id: np.ndarray,
    was_rejected: np.ndarray,
    g_unique_ids: np.ndarray,
    probe_unique_ids: np.ndarray,
    fractions: np.ndarray,
    seed: int,
) -> Dict[str, float]:
    masks = compute_osr_error_masks(
        predicted_id, was_rejected, g_unique_ids, probe_unique_ids
    )
    prr, _, _, _ = self_normalized_prr(
        uncertainty=uncertainty,
        predicted_id=predicted_id,
        was_rejected=was_rejected,
        g_unique_ids=g_unique_ids,
        probe_unique_ids=probe_unique_ids,
        fractions=fractions,
        metric_name="f1_class",
        seed=seed,
    )
    return {
        "prr_f1": float(prr),
        "error_auroc": safe_auc(masks["any_error"], uncertainty),
        "error_auprc": safe_auprc(masks["any_error"], uncertainty),
        "error_rate": float(np.mean(masks["any_error"])),
    }


def recognition_metrics(result: Dict[str, Any]) -> Dict[str, float]:
    f1 = f1_classic(
        result["predicted_id"],
        result["was_rejected"],
        result["g_unique_ids"],
        result["probe_unique_ids"],
    )
    fnir, fpir = fnir_fpir(
        result["predicted_id"],
        result["was_rejected"],
        result["g_unique_ids"],
        result["probe_unique_ids"],
    )
    return {"f1": f1, "fnir": fnir, "fpir": fpir}


def raw_kl_from_pooled(
    base_method_cfg,
    arrays: Dict[str, np.ndarray],
    *,
    mode: str,
    T: float,
    M: int,
    beta: float,
    gallery_kappa: float,
    kappa_input_scale: float,
    seed: int,
    mc_num_workers: int,
):
    seed_everything(seed=seed, deterministic=True)
    method_cfg = prepare_holue_cfg(
        base_method_cfg,
        mode=mode,
        T=T,
        M=M,
        gallery_kappa=gallery_kappa,
        use_calibrator=False,
        mc_num_workers=mc_num_workers,
    )
    rm = instantiate(method_cfg.recognition_method)
    rm.beta = float(beta)

    probe_unc_scaled = arrays["probe_unc"] * float(kappa_input_scale)
    gallery_unc_scaled = np.ones_like(arrays["gallery_unc"]) * float(gallery_kappa)
    mean_probs, kl_1, kl_2 = rm.compute_mean_probs_and_kl(
        arrays["probe_feats"],
        probe_unc_scaled,
        arrays["gallery_feats"],
        gallery_unc_scaled,
        float(T),
    )
    mean_probs = mean_probs.detach().cpu().numpy()
    kl_1 = kl_1.detach().cpu().numpy().reshape(-1)
    kl_2 = kl_2.detach().cpu().numpy().reshape(-1)
    return {
        "mean_probs": mean_probs,
        "kl_1": kl_1,
        "kl_2": kl_2,
        "uncertainty": -(kl_1 + kl_2),
    }


def normalization_audit_from_pooled(
    base_method_cfg,
    arrays: Dict[str, np.ndarray],
    *,
    T: float,
    M: int,
    beta: float,
    gallery_kappa: float,
    kappa_input_scale: float,
    seed: int,
    mc_num_workers: int,
):
    seed_everything(seed=seed, deterministic=True)
    method_cfg = prepare_holue_cfg(
        base_method_cfg,
        mode="normalized",
        T=T,
        M=M,
        gallery_kappa=gallery_kappa,
        use_calibrator=False,
        mc_num_workers=mc_num_workers,
    )
    rm = instantiate(method_cfg.recognition_method)
    rm.beta = float(beta)

    probe_unc_scaled = arrays["probe_unc"] * float(kappa_input_scale)
    gallery_unc_scaled = np.ones_like(arrays["gallery_unc"]) * float(gallery_kappa)
    diag = rm.compute_temperature_scaling_diagnostics(
        arrays["probe_feats"],
        probe_unc_scaled,
        arrays["gallery_feats"],
        gallery_unc_scaled,
        float(T),
    )
    return {k: v.detach().cpu().numpy().reshape(-1) for k, v in diag.items()}


def quantile_bins(values: np.ndarray, quantiles: List[float]) -> Tuple[np.ndarray, np.ndarray]:
    values = np.asarray(values, dtype=np.float64).reshape(-1)
    edges = np.quantile(values, np.asarray(quantiles, dtype=np.float64))
    edges = np.maximum.accumulate(edges)
    # np.digitize requires internal cut points; duplicated cuts are harmless but
    # can create empty bins, which are skipped by the caller.
    bins = np.digitize(values, edges[1:-1], right=True)
    return bins, edges



def empirical_ks_distance(a: np.ndarray, b: np.ndarray) -> float:
    """Two-sample Kolmogorov--Smirnov distance without an extra dependency."""
    a = np.sort(np.asarray(a, dtype=np.float64).reshape(-1))
    b = np.sort(np.asarray(b, dtype=np.float64).reshape(-1))
    if len(a) == 0 or len(b) == 0:
        return float("nan")
    support = np.sort(np.concatenate([a, b]))
    cdf_a = np.searchsorted(a, support, side="right") / float(len(a))
    cdf_b = np.searchsorted(b, support, side="right") / float(len(b))
    return float(np.max(np.abs(cdf_a - cdf_b)))


def quality_shift_row(
    *,
    dataset_name: str,
    validation_name: str,
    test_kappa: np.ndarray,
    validation_kappa: np.ndarray,
) -> Dict[str, Any]:
    """Summarize the SCF-concentration shift between validation and test sets.

    This is particularly important for IJB-B/IJB-C because their validation
    embeddings are produced from the deliberately quality-filtered MS1MV2 set.
    The statistic is descriptive only; it is never used to choose parameters on
    the test set.
    """
    test = np.asarray(test_kappa, dtype=np.float64).reshape(-1)
    val = np.asarray(validation_kappa, dtype=np.float64).reshape(-1)
    if len(test) == 0 or len(val) == 0:
        raise ValueError("Quality-shift audit requires non-empty validation and test arrays.")

    qs = np.asarray([0.10, 0.25, 0.50, 0.75, 0.90], dtype=np.float64)
    test_q = np.quantile(test, qs)
    val_q = np.quantile(val, qs)

    # Quantile-L1 is an interpretable 1-D distribution-shift summary in the
    # physical SCF-concentration scale.  KS is scale-free and invariant to any
    # monotone reparameterization of kappa.
    dense_q = np.linspace(0.0, 1.0, 1001)
    quantile_l1 = float(
        np.mean(np.abs(np.quantile(test, dense_q) - np.quantile(val, dense_q)))
    )

    row: Dict[str, Any] = {
        "dataset": str(dataset_name),
        "validation_dataset": str(validation_name),
        "n_test": int(len(test)),
        "n_validation": int(len(val)),
        "test_mean_kappa": float(np.mean(test)),
        "validation_mean_kappa": float(np.mean(val)),
        "test_std_kappa": float(np.std(test)),
        "validation_std_kappa": float(np.std(val)),
        "ks_distance": empirical_ks_distance(test, val),
        "quantile_l1_distance": quantile_l1,
    }
    for q, tq, vq in zip(qs, test_q, val_q):
        label = int(round(100 * float(q)))
        row[f"test_q{label:02d}"] = float(tq)
        row[f"validation_q{label:02d}"] = float(vq)
    return row


def quality_stratified_rows(
    *,
    dataset_name: str,
    far: float,
    beta: float,
    raw_kappa: np.ndarray,
    scores: Dict[str, np.ndarray],
    predicted_id: np.ndarray,
    was_rejected: np.ndarray,
    g_unique_ids: np.ndarray,
    probe_unique_ids: np.ndarray,
    fractions: np.ndarray,
    quantiles: List[float],
    seed: int,
) -> List[Dict[str, Any]]:
    kappa = np.asarray(raw_kappa, dtype=np.float64).reshape(-1)
    bins, edges = quantile_bins(kappa, quantiles)
    rows = []
    for b in range(len(edges) - 1):
        idx = np.flatnonzero(bins == b)
        if len(idx) < 2:
            continue
        for name, score in scores.items():
            metrics = uncertainty_metrics(
                uncertainty=np.asarray(score)[idx],
                predicted_id=np.asarray(predicted_id)[idx],
                was_rejected=np.asarray(was_rejected)[idx],
                g_unique_ids=g_unique_ids,
                probe_unique_ids=np.asarray(probe_unique_ids)[idx],
                fractions=fractions,
                seed=seed,
            )
            rows.append(
                {
                    "dataset": dataset_name,
                    "far": float(far),
                    "beta": float(beta),
                    "score": name,
                    "quality_bin": int(b),
                    "count": int(len(idx)),
                    "kappa_min": float(np.min(kappa[idx])),
                    "kappa_max": float(np.max(kappa[idx])),
                    "kappa_mean": float(np.mean(kappa[idx])),
                    **metrics,
                }
            )
    return rows


def save_rows(rows: List[Dict[str, Any]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(path, index=False)
    print(f"[saved] {path}")


@hydra.main(
    config_path=str(Path(__file__).resolve().parents[1] / "configs/uncertainty_benchmark"),
    config_name="holue_temperature_scaling_bio",
    version_base="1.2",
)
def main(cfg):
    seed = int(cfg.get("seed", 777))
    seed_everything(seed=seed, deterministic=bool(cfg.get("deterministic", True)))

    study = cfg.holue_temperature_study
    out_dir = Path(cfg.exp_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    fractions = fractions_from_cfg(cfg)

    base_holue_cfg = find_holue_method_cfg(cfg)
    # Do not pass OmegaConf attribute access as ``dict.get`` defaults here:
    # Python evaluates default arguments eagerly, so a config where ``M`` is
    # intentionally omitted (MonteCarloPredictiveProb defaults to M=0) would
    # fail before ``study.published_M`` can be read.
    if "published_T" in study:
        published_T = float(study.published_T)
    else:
        published_T = float(base_holue_cfg.recognition_method.get("predict_T", 1.0))

    if "published_M" in study:
        published_M = int(study.published_M)
    else:
        published_M = int(base_holue_cfg.recognition_method.get("M", 0))
    mc_num_workers = int(study.get("mc_num_workers", 1))

    datasets = instantiate_list(cfg.test_datasets)

    final_rows: List[Dict[str, Any]] = []
    ranking_rows: List[Dict[str, Any]] = []
    normalization_rows: List[Dict[str, Any]] = []
    temperature_rows: List[Dict[str, Any]] = []
    mc_rows: List[Dict[str, Any]] = []
    quality_rows: List[Dict[str, Any]] = []
    quality_shift_rows: List[Dict[str, Any]] = []

    per_example_dir = out_dir / "per_example_npz"
    per_example_dir.mkdir(parents=True, exist_ok=True)

    for dataset in datasets:
        dataset_name = str(dataset.dataset_name)
        for far in cfg.far_list:
            far = float(far)
            for beta in cfg.beta_list:
                beta = float(beta)
                print("=" * 100)
                print(
                    f"[HolUETemperature] dataset={dataset_name} far={far} beta={beta}"
                )
                print("=" * 100)

                # ----------------------------------------------------------
                # A. Final HolUE comparison: same published T/M, retrain the
                #    calibration transform separately for each formula.
                # ----------------------------------------------------------
                full_results = {}
                full_tts = {}
                for mode in ["normalized", "legacy_paper"]:
                    method_cfg = prepare_holue_cfg(
                        base_holue_cfg,
                        mode=mode,
                        T=published_T,
                        M=published_M,
                        use_calibrator=True,
                        mc_num_workers=mc_num_workers,
                    )
                    variant_name = f"HolUE {mode}"
                    tt, result = run_full_variant(
                        cfg,
                        dataset=dataset,
                        method_cfg=method_cfg,
                        far=far,
                        beta=beta,
                        variant_name=variant_name,
                        out_dir=out_dir,
                    )
                    full_results[mode] = result
                    full_tts[mode] = tt

                    um = uncertainty_metrics(
                        uncertainty=result["predicted_unc"],
                        predicted_id=result["predicted_id"],
                        was_rejected=result["was_rejected"],
                        g_unique_ids=result["g_unique_ids"],
                        probe_unique_ids=result["probe_unique_ids"],
                        fractions=fractions,
                        seed=seed,
                    )
                    final_rows.append(
                        {
                            "dataset": dataset_name,
                            "far": far,
                            "beta": beta,
                            "mode": mode,
                            "T": published_T,
                            "M": published_M,
                            **recognition_metrics(result),
                            **um,
                        }
                    )

                    rm = result["recognition_method"]
                    np.savez(
                        per_example_dir
                        / f"{slugify(dataset_name)}_far_{far}_beta_{beta}_{mode}.npz",
                        predicted_id=result["predicted_id"],
                        was_rejected=result["was_rejected"],
                        predicted_unc=result["predicted_unc"],
                        probe_unique_ids=result["probe_unique_ids"],
                        g_unique_ids=result["g_unique_ids"],
                        kl_1=np.asarray(rm.kl_1),
                        kl_2=np.asarray(rm.kl_2),
                        mean_probs=np.asarray(rm.mean_probs),
                    )

                proper = full_results["normalized"]
                legacy = full_results["legacy_paper"]
                ranking_rows.append(
                    {
                        "dataset": dataset_name,
                        "far": far,
                        "beta": beta,
                        "comparison": "final_calibrated_normalized_vs_legacy",
                        "spearman": safe_spearman(
                            proper["predicted_unc"], legacy["predicted_unc"]
                        ),
                        "rank_inversion_rate": sampled_rank_inversion_rate(
                            proper["predicted_unc"],
                            legacy["predicted_unc"],
                            num_pairs=int(study.get("rank_pairs", 200000)),
                            seed=seed,
                        ),
                        "decision_disagreement_rate": float(
                            np.mean(
                                np.logical_or(
                                    proper["predicted_id"] != legacy["predicted_id"],
                                    proper["was_rejected"] != legacy["was_rejected"],
                                )
                            )
                        ),
                    }
                )

                # All raw studies use one fixed OSR decision and one fixed
                # gallery concentration, so they measure uncertainty only.
                ref_tt = full_tts["normalized"]
                ref_rm = proper["recognition_method"]
                arrays = pooled_arrays(ref_tt)
                fixed_predicted_id = proper["predicted_id"]
                fixed_was_rejected = proper["was_rejected"]
                fixed_gallery_kappa = float(ref_rm.gallery_kappa)
                kappa_input_scale = float(getattr(ref_rm, "kappa_input_scale", 1.0))

                # ----------------------------------------------------------
                # B. Normalization audit.  Use MC samples to estimate the
                #    continuous mass, while normalized mass is exactly one for
                #    every finite sample set by construction.
                # ----------------------------------------------------------
                for T in study.temperature_grid:
                    diag = normalization_audit_from_pooled(
                        base_holue_cfg,
                        arrays,
                        T=float(T),
                        M=int(study.mass_audit_M),
                        beta=beta,
                        gallery_kappa=fixed_gallery_kappa,
                        kappa_input_scale=kappa_input_scale,
                        seed=seed,
                        mc_num_workers=mc_num_workers,
                    )
                    for mode, key in [
                        ("normalized", "normalized_total_mass"),
                        ("legacy_paper", "legacy_total_mass"),
                    ]:
                        mass = diag[key]
                        normalization_rows.append(
                            {
                                "dataset": dataset_name,
                                "far": far,
                                "beta": beta,
                                "mode": mode,
                                "T": float(T),
                                "M": int(study.mass_audit_M),
                                "mean_total_mass": float(np.mean(mass)),
                                "std_total_mass": float(np.std(mass)),
                                "mean_abs_mass_defect": float(np.mean(np.abs(mass - 1.0))),
                                "max_abs_mass_defect": float(np.max(np.abs(mass - 1.0))),
                                "p95_abs_mass_defect": float(
                                    np.quantile(np.abs(mass - 1.0), 0.95)
                                ),
                            }
                        )

                # ----------------------------------------------------------
                # C. Temperature sensitivity of raw KL features.  No MLP and
                #    no retuning of the recognizer/gallery kappa.
                # ----------------------------------------------------------
                raw_by_mode_T: Dict[Tuple[str, float], Dict[str, np.ndarray]] = {}
                for mode in ["normalized", "legacy_paper"]:
                    for T in study.temperature_grid:
                        raw = raw_kl_from_pooled(
                            base_holue_cfg,
                            arrays,
                            mode=mode,
                            T=float(T),
                            M=published_M,
                            beta=beta,
                            gallery_kappa=fixed_gallery_kappa,
                            kappa_input_scale=kappa_input_scale,
                            seed=seed,
                            mc_num_workers=mc_num_workers,
                        )
                        raw_by_mode_T[(mode, float(T))] = raw
                        um = uncertainty_metrics(
                            uncertainty=raw["uncertainty"],
                            predicted_id=fixed_predicted_id,
                            was_rejected=fixed_was_rejected,
                            g_unique_ids=arrays["g_unique_ids"],
                            probe_unique_ids=arrays["probe_unique_ids"],
                            fractions=fractions,
                            seed=seed,
                        )
                        temperature_rows.append(
                            {
                                "dataset": dataset_name,
                                "far": far,
                                "beta": beta,
                                "mode": mode,
                                "T": float(T),
                                "M": published_M,
                                "gallery_kappa_fixed": fixed_gallery_kappa,
                                "kl1_mean": float(np.mean(raw["kl_1"])),
                                "kl1_std": float(np.std(raw["kl_1"])),
                                "kl2_mean": float(np.mean(raw["kl_2"])),
                                "kl2_std": float(np.std(raw["kl_2"])),
                                **um,
                            }
                        )

                    ref_raw = raw_by_mode_T[(mode, published_T)]
                    for T in study.temperature_grid:
                        raw = raw_by_mode_T[(mode, float(T))]
                        ranking_rows.append(
                            {
                                "dataset": dataset_name,
                                "far": far,
                                "beta": beta,
                                "comparison": f"raw_{mode}_T{float(T)}_vs_T{published_T}",
                                "spearman": safe_spearman(
                                    raw["uncertainty"], ref_raw["uncertainty"]
                                ),
                                "rank_inversion_rate": sampled_rank_inversion_rate(
                                    raw["uncertainty"],
                                    ref_raw["uncertainty"],
                                    num_pairs=int(study.get("rank_pairs", 200000)),
                                    seed=seed,
                                ),
                                "decision_disagreement_rate": 0.0,
                            }
                        )

                # ----------------------------------------------------------
                # D. MC convergence. Repeat stochastic runs over several seeds.
                #    Decisions stay fixed to the standard M=0 recognizer.
                # ----------------------------------------------------------
                for M in study.mc_grid:
                    for mc_seed in study.mc_seeds:
                        raw = raw_kl_from_pooled(
                            base_holue_cfg,
                            arrays,
                            mode="normalized",
                            T=published_T,
                            M=int(M),
                            beta=beta,
                            gallery_kappa=fixed_gallery_kappa,
                            kappa_input_scale=kappa_input_scale,
                            seed=int(mc_seed),
                            mc_num_workers=mc_num_workers,
                        )
                        um = uncertainty_metrics(
                            uncertainty=raw["uncertainty"],
                            predicted_id=fixed_predicted_id,
                            was_rejected=fixed_was_rejected,
                            g_unique_ids=arrays["g_unique_ids"],
                            probe_unique_ids=arrays["probe_unique_ids"],
                            fractions=fractions,
                            seed=seed,
                        )
                        mc_rows.append(
                            {
                                "dataset": dataset_name,
                                "far": far,
                                "beta": beta,
                                "T": published_T,
                                "M": int(M),
                                "mc_seed": int(mc_seed),
                                "kl1_mean": float(np.mean(raw["kl_1"])),
                                "kl2_mean": float(np.mean(raw["kl_2"])),
                                **um,
                            }
                        )

                # ----------------------------------------------------------
                # E. Quality stratification for final calibrated scores.
                # ----------------------------------------------------------
                quality_rows.extend(
                    quality_stratified_rows(
                        dataset_name=dataset_name,
                        far=far,
                        beta=beta,
                        raw_kappa=arrays["probe_unc"],
                        scores={
                            "normalized": proper["predicted_unc"],
                            "legacy_paper": legacy["predicted_unc"],
                        },
                        predicted_id=fixed_predicted_id,
                        was_rejected=fixed_was_rejected,
                        g_unique_ids=arrays["g_unique_ids"],
                        probe_unique_ids=arrays["probe_unique_ids"],
                        fractions=fractions,
                        quantiles=[float(q) for q in study.quality_quantiles],
                        seed=seed,
                    )
                )

                # ----------------------------------------------------------
                # F. Validation-to-test SCF-quality shift.  Record it once per
                #    test dataset; it does not depend on FAR or beta.
                # ----------------------------------------------------------
                if (
                    far == float(cfg.far_list[0])
                    and beta == float(cfg.beta_list[0])
                    and getattr(ref_rm, "data_uncertainty_calib", None) is not None
                ):
                    validation_name = str(
                        getattr(getattr(ref_rm, "calibration_set", None), "dataset_name", "validation")
                    )
                    quality_shift_rows.append(
                        quality_shift_row(
                            dataset_name=dataset_name,
                            validation_name=validation_name,
                            test_kappa=arrays["probe_unc"],
                            validation_kappa=np.asarray(ref_rm.data_uncertainty_calib),
                        )
                    )


    save_rows(final_rows, out_dir / "tables" / "final_formula_comparison.csv")
    save_rows(ranking_rows, out_dir / "tables" / "ranking_stability.csv")
    save_rows(normalization_rows, out_dir / "tables" / "normalization_audit.csv")
    save_rows(temperature_rows, out_dir / "tables" / "temperature_sensitivity.csv")
    save_rows(mc_rows, out_dir / "tables" / "mc_convergence.csv")
    save_rows(quality_rows, out_dir / "tables" / "quality_stratified.csv")
    save_rows(quality_shift_rows, out_dir / "tables" / "quality_shift.csv")

    summary = {
        "temperature_scaling_default": "normalized",
        "published_T": published_T,
        "published_M": published_M,
        "mass_audit_M": int(study.mass_audit_M),
        "temperature_grid": [float(x) for x in study.temperature_grid],
        "mc_grid": [int(x) for x in study.mc_grid],
        "mc_seeds": [int(x) for x in study.mc_seeds],
        "notes": [
            "Final normalized-vs-legacy comparison retrains the HolUE calibrator per formula.",
            "Temperature and MC studies keep recognizer decisions and gallery kappa fixed.",
            "legacy_paper is a reproducibility ablation and must not be used in final dissertation results.",
        ],
    }
    with open(out_dir / "study_manifest.json", "w") as f:
        json.dump(summary, f, indent=2)


