#!/usr/bin/env python3
"""HolUE temperature-scaling validation experiments for the dissertation.

This runner deliberately excludes ``modern_ai`` code and uses the existing
biometric/text open-set recognition protocols only.

It answers six questions that should be documented when the HolUE results are
regenerated:

1. Does the accepted-paper temperature formula define a normalized mixed
   posterior?  (No in general; measured by ``normalization_audit.csv``.)
2. How much do final calibrated HolUE results change when the continuous term
   uses the normalized denominator instead of the accepted-paper denominator?
3. How sensitive is the *raw* KL uncertainty ranking to temperature when the
   recognizer and gallery concentration are held fixed?
4. Is the deterministic mean-embedding approximation (M=0) adequate relative
   to Monte Carlo integration?
5. Are differences concentrated in low-SCF-concentration probes?
6. How large is the SCF-concentration distribution shift between each validation
   set and its test set (especially filtered MS1MV2 versus IJB-B/IJB-C)?

The standard dissertation tables should still be regenerated by the normal
core experiment scripts after this patch.  This runner is an audit/ablation
suite, not a replacement for the core tables.
"""
